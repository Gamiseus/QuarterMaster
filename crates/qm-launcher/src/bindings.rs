/// 64-bit integers (sizes, timestamps) are exported as `number`; values stay below 2^53.
pub fn typescript() -> Typescript {
    Typescript::default()
        .bigint(BigIntExportBehavior::Number)
        .header("// Generated by qm-launcher (tests/bindings.rs). Do not edit.")
}

/// The full `bindings.ts` contents.
pub fn export_bindings() -> Result<String, specta_typescript::ExportError> {
    specta_builder().export_str(typescript())
}
