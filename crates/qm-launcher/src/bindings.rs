//! tauri-specta builder: every command plus the `qm://event` payload type.
use crate::commands::*;
use crate::sink::QmEventPayload;
use specta_typescript::{BigIntExportBehavior, Typescript};
use tauri_specta::{collect_commands, collect_events, Builder};

pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            app_info,
            settings_get,
            settings_update,
            paths_auto_detect,
            onboarding_complete,
            reveal,
            startup_status,
            profiles_list,
            profile_get,
            profile_preview_switch,
            profile_create,
            profile_rename,
            profile_update,
            profile_delete,
            profile_clone,
            profile_activate,
            profile_export_code,
            profile_import_code,
            mods_list,
            mod_detail,
            mod_patches_get,
            mod_set_enabled,
            mod_config_set,
            mod_config_reset,
            mod_import_inspect,
            mod_import,
            mod_uninstall,
            load_order_get,
            simulation_get,
            file_diff_get,
            load_order_set,
            patch_set_enabled,
            conflict_resolve,
            saves_list,
            save_detail,
            saves_compare,
            save_activate,
            save_clone,
            save_backup,
            save_restore,
            save_delete_backup,
            game_status,
            game_launch,
            game_restore_clean,
            health_get,
            crashes_list,
            logs_tail,
            diagnostic_bundle_build,
            crash_disable_suspect,
            dll_repair,
            updates_get,
            updates_refresh,
            catalog_get,
            catalog_refresh,
            catalog_install,
            launcher_update_download,
            launcher_update_apply,
            launcher_update_rollback,
            jobs_list,
            job_cancel,
        ])
        .events(collect_events![QmEventPayload])
}

/// 64-bit integers (sizes, timestamps) are exported as `number`; values stay below 2^53.
pub fn typescript() -> Typescript {
    Typescript::default()
        .bigint(BigIntExportBehavior::Number)
        .header("// Generated by qm-launcher (tests/bindings.rs). Do not edit.")
}

/// The full `bindings.ts` contents.
pub fn export_bindings() -> Result<String, specta_typescript::ExportError> {
    specta_builder().export_str(typescript())
}
